#!/usr/bin/env python3
"""Driving cameras for SPEC-CAMERAS (docs/specs/CAMERAS.md).

Two commands, both our own tooling; nothing here contains game data:

    python -I tools/re/cameras.py route --car R34 --dumps <dir> --output <route>
    python -I tools/re/cameras.py analyse --media NIS_SkylineGTRVSpecII_02 <dump>...

`route` writes a render-test route for a pinned free-roam seed: wake the
car, set the immersive camera mod's layers to 0, then take frame dumps
parked in each camera the right shoulder cycles to (two per camera, for
the idle spread), with the right stick held for look back, left and
right, and in the chase cameras and the others on a straight cruise.

`analyse` reads frame dumps (tools/re/world-geometry.py) and prints, per
dump, the eye in the car's draw frame and the vertical field of view. The
car's draws are found by the bytes of its LOD0 and cockpit vertex pools
(as tools/re/autoshow_dump.py does); in free roam vertex constants c0-c3
hold the columns of their clip-from-model matrix and c4-c7 those of
view-from-model, so the eye in the model frame is -R^T t of the view
matrix and the lens comes from the clip matrix's x and y rows across its
w row. The model frame is FORMAT-CARS car space with z negated. The
bumper camera's view draws no car; for it, read the camera position
constant c158 against the car draws' model-to-world c8-c11.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import math
import struct
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


# --- route ---------------------------------------------------------------------

RB = 0x0200
A = 0x1000


def route(args) -> None:
    dumps = Path(args.dumps).resolve()
    dumps.mkdir(parents=True, exist_ok=True)
    lines = ["pinyon-shift-fh1-render-test-v1", "# clock-hz 60",
             f"# SPEC-CAMERAS oracle ({args.car}): generated by tools/re/cameras.py route.",
             "# Run hidden with --game-argument=--pinyon_shift_physics_trace=6."]
    events: list[tuple[int, str]] = []
    for n, name in enumerate(("gforce", "lean", "shake", "head")):
        events.append((n, f"cvar {n} pinyon_shift_camera_{name} 0"))
    pad = {"buttons": 0, "rt": 0, "rx": 0, "ry": 0}
    inputs: dict[int, dict] = {}

    def put(frame, **kw):
        state = dict(pad)
        state.update(kw)
        pad.update(kw)
        inputs[frame] = dict(state)

    put(0)
    for f in (360, 480, 600, 720):
        put(f, buttons=A)
        put(f + 6, buttons=0)
    put(780)
    events.append((900, "wait 900 3000 vehicle"))

    def dump(frame, label):
        events.append((frame - 4, f"cvar {frame - 4} fh1_frame_dump_path {dumps / (label + '.fh1frame')}"))
        events.append((frame, f"cvar {frame} fh1_frame_dump_frame -1"))
        events.append((frame + 1, f"capture {frame + 1} {label}"))

    def press(frame, buttons=RB):
        put(frame, buttons=buttons)
        put(frame + 6, buttons=0)

    t = args.start
    # Parked: the default camera, then each press of the right shoulder.
    for k in range(6):
        if k:
            press(t)
            t += 150
        dump(t, f"park-{k}a")
        dump(t + 40, f"park-{k}b")
        t += 100
    # Look back, left and right in the default (wrapped) camera.
    for label, rx, ry in (("look-back", 0, -32768), ("look-left", -32768, 0), ("look-right", 32767, 0)):
        put(t, rx=rx, ry=ry)
        dump(t + 60, label)
        put(t + 80, rx=0, ry=0)
        t += 140
    if args.parked_only:
        events.append((t + 60, f"stop {t + 60}"))
    else:
        # Cruise: part throttle, no steering; two dumps in the first
        # camera, then one in each other camera.
        put(t, rt=args.throttle)
        t += 600
        dump(t, "cruise-0a")
        t += 300
        dump(t, "cruise-0b")
        for k in range(1, 5):
            press(t + 20)
            t += 160
            dump(t, f"cruise-{k}")
        put(t + 40, rt=0)
        events.append((t + 200, f"stop {t + 200}"))
    for frame, s in inputs.items():
        events.append((frame, f"input {frame} {s['buttons']:04x} 0 {s['rt']} 0 0 {s['rx']} {s['ry']}"))
    events.sort(key=lambda e: (e[0], not e[1].startswith("cvar")))
    Path(args.output).write_text("\n".join(lines + [e for _, e in events]) + "\n", encoding="utf-8")
    print(f"wrote {args.output}")


# --- analysis ------------------------------------------------------------------

def floats(words) -> list[float]:
    return list(struct.unpack(f"<{len(words)}f", struct.pack(f"<{len(words)}I", *words)))


def lens(m) -> dict:
    """Vertical and horizontal field of view of a clip matrix (rows clip x,
    y, z, w): the w row's xyz length over the x and y rows' parts across
    it."""
    rows = [m[0:4], m[4:8], m[8:12], m[12:16]]
    w = rows[3][:3]
    wn = math.sqrt(sum(v * v for v in w))
    f = [v / wn for v in w]
    out = {}
    for name, r in (("h", rows[0]), ("v", rows[1])):
        c = sum(a * b for a, b in zip(r[:3], f))
        rest = [a - c * b for a, b in zip(r[:3], f)]
        s = math.sqrt(sum(v * v for v in rest)) / wn
        out[name] = math.degrees(2 * math.atan(1 / s))
    return out


def analyse(args) -> None:
    ad = _load("autoshow_dump", ROOT / "tools/re/autoshow_dump.py")
    wg = ad.wg
    keys = ad.model_keys(ad.car_folder(args.media), "car")
    results = []
    for path in args.dumps:
        registers, packets, blocks = wg.read_frame_dump(str(path))
        memory = wg.GuestMemory(blocks)
        draws = wg.walk_draws(registers, packets, memory, predicate=True, constants=True)
        scene = Counter(d["mvp"] for d in draws).most_common(1)[0][0]
        found = Counter()
        for d in draws:
            for _, address, _ in d["fetch"]:
                k = keys.get(memory.read(address, ad.KEY))
                if k:
                    label = ad.part_label(k[0], k[1])
                    c = floats(d["vs_constants"][0:64])
                    # Constants c0-c3 are the columns of clip-from-model and
                    # c4-c7 the columns of view-from-model; c11 the model's
                    # world position, c158 the camera's.
                    clip = tuple(round(c[4 * col + r], 7) for r in range(4) for col in range(4))
                    view = tuple(round(c[16 + 4 * col + r], 7) for r in range(4) for col in range(4))
                    found[(label, clip, view)] += 1
                    break
        row = {"dump": Path(path).stem, "scene_fov": {k: round(v, 3) for k, v in lens(scene).items()},
               "parts": {}}
        for (label, clip, view), n in found.most_common():
            if label in row["parts"]:
                continue
            r = [[view[4 * i + j] for j in range(3)] for i in range(3)]
            t = [view[4 * i + 3] for i in range(3)]
            if abs(view[15] - 1) > 1e-3 or max(abs(v) for v in clip[12:15]) < 1e-3:
                continue          # not a perspective draw of the main view
            eye = [-sum(r[i][j] * t[i] for i in range(3)) for j in range(3)]
            fwd = [r[2][j] for j in range(3)]      # view z axis in model space
            row["parts"][label] = {"draws": n, "eye": [round(v, 4) for v in eye],
                                   "view_z": [round(v, 4) for v in fwd],
                                   "fov": {k: round(v, 3) for k, v in lens(clip).items()}}
        results.append(row)
        print(json.dumps(row))
    if args.output:
        Path(args.output).write_text(json.dumps(results, indent=1), encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    r = sub.add_parser("route")
    r.add_argument("--car", required=True)
    r.add_argument("--dumps", required=True)
    r.add_argument("--output", required=True)
    r.add_argument("--throttle", type=int, default=90)
    r.add_argument("--start", type=int, default=1100,
                   help="frame of the first parked dump; later than the car's landing")
    r.add_argument("--parked-only", action="store_true")
    r.set_defaults(func=route)
    a = sub.add_parser("analyse")
    a.add_argument("--media", required=True)
    a.add_argument("--output")
    a.add_argument("dumps", nargs="+", type=Path)
    a.set_defaults(func=analyse)
    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
